export function getChantiersById(id: string): Chantier | undefined {
  return mockChantiers.find(c => c.id === id);
}

export function getChantiersParClient(clientId: string): Chantier[] {
  return mockChantiers.filter(c => c.clientId === clientId);
}

export function getChantiersParStatut(statut: Chantier['statut']): Chantier[] {
  return mockChantiers.filter(c => c.statut === statut);
}

export function getChantiersEnCours(): Chantier[] {
  return mockChantiers.filter(c => c.statut === 'EN_COURS');
}

export function getChantiersTermines(): Chantier[] {
  return mockChantiers.filter(c => c.statut === 'TERMINE');
}

export function getTotalChiffresAffaires(): number {
  return mockChantiers.reduce((sum, c) => sum + (c.montantReel || c.montantEstime), 0);
}
